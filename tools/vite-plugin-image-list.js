/**
 * Vite Plugin: Dynamic Image List Generator
 *
 * Automatically scans specified directories for image files and generates
 * JavaScript modules containing arrays of image filenames at build time.
 *
 * Features:
 * - Scans directories recursively for image files
 * - Configurable file extensions and output locations
 * - Generates ES modules with named/default exports
 * - Hot-reload support in development
 * - Cross-platform path handling
 *
 * Usage:
 * import { imageListPlugin } from '../../../tools/vite-plugin-image-list.js'
 *
 * export default {
 *   plugins: [
 *     imageListPlugin({
 *       scanDir: 'public/images',
 *       outputFile: 'src/generated/images.js',
 *       extensions: ['.png', '.jpg', '.jpeg', '.gif', '.webp'],
 *       exportName: 'imgs'
 *     })
 *   ]
 * }
 */

import { readdir, writeFile, mkdir } from 'fs/promises'
import { join, dirname, extname } from 'path'
import { existsSync } from 'fs'

export function imageListPlugin (options = {}) {
  const {
    scanDir = 'public/images',
    outputFile = 'src/generated/images.js',
    extensions = ['.png', '.jpg', '.jpeg', '.gif', '.webp', '.svg'],
    exportName = 'images',
    recursive = true
  } = options

  let root = ''
  let isServing = false

  return {
    name: 'image-list-generator',

    configResolved (config) {
      root = config.root
      isServing = config.command === 'serve'
    },

    async buildStart () {
      await generateImageList()
    },

    async handleHotUpdate ({ file, server }) {
      // Only trigger regeneration if an image file was added/removed in the scan directory
      const scanPath = join(root, scanDir)
      if (file.startsWith(scanPath) && extensions.includes(extname(file))) {
        await generateImageList()

        // Trigger reload of the generated module
        const outputPath = join(root, outputFile)
        const module = server.moduleGraph.getModuleById(outputPath)
        if (module) {
          server.reloadModule(module)
        }
      }
    },

    async generateImageList () {
      const scanPath = join(root, scanDir)
      const outputPath = join(root, outputFile)

      try {
        const imageFiles = await scanImagesRecursively(scanPath, extensions, recursive)
        await generateModule(imageFiles, outputPath, exportName, scanDir)

        if (isServing) {
          console.log(`🖼️  Generated image list: ${imageFiles.length} images found`)
        }
      } catch (error) {
        console.error(`Failed to generate image list: ${error.message}`)
        throw error
      }
    }
  }

  async function generateImageList () {
    const scanPath = join(root, scanDir)
    const outputPath = join(root, outputFile)

    try {
      const imageFiles = await scanImagesRecursively(scanPath, extensions, recursive)
      await generateModule(imageFiles, outputPath, exportName, scanDir)

      if (isServing) {
        console.log(`🖼️  Generated image list: ${imageFiles.length} images found`)
      }
    } catch (error) {
      console.error(`Failed to generate image list: ${error.message}`)
      throw error
    }
  }
}

/**
 * Recursively scan directory for image files
 */
async function scanImagesRecursively (dir, extensions, recursive = true) {
  const imageFiles = []
  
  if (!existsSync(dir)) {
    console.warn(`Image directory not found: ${dir}`)
    return imageFiles
  }

  try {
    const entries = await readdir(dir, { withFileTypes: true })
    
    for (const entry of entries) {
      const fullPath = join(dir, entry.name)
      
      if (entry.isDirectory() && recursive) {
        // Recursively scan subdirectories
        const subImages = await scanImagesRecursively(fullPath, extensions, recursive)
        imageFiles.push(...subImages)
      } else if (entry.isFile()) {
        const ext = extname(entry.name).toLowerCase()
        if (extensions.includes(ext)) {
          imageFiles.push(entry.name)
        }
      }
    }
  } catch (error) {
    console.error(`Error scanning directory ${dir}:`, error.message)
  }

  // Sort for consistent ordering
  return imageFiles.sort()
}

/**
 * Generate JavaScript module with image list
 */
async function generateModule (imageFiles, outputPath, exportName, baseDir) {
  // Ensure output directory exists
  const outputDir = dirname(outputPath)
  if (!existsSync(outputDir)) {
    await mkdir(outputDir, { recursive: true })
  }

  // Generate module content
  const moduleContent = `/**
 * Auto-generated image list
 *
 * This file is automatically generated by vite-plugin-image-list.
 * Do not edit manually - changes will be overwritten.
 *
 * Source directory: ${baseDir}
 * Generated: ${new Date().toISOString()}
 * Total images: ${imageFiles.length}
 */

export const ${exportName} = [\n${imageFiles.map(f => `  '${f}'`).join(',\n')}\n]

// Default export for convenience
export default ${exportName}
`

  await writeFile(outputPath, moduleContent, 'utf8')
}