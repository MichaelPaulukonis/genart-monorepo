#!/usr/bin/env node
// Simple workspace changelog aggregator for Nx independent-project workspaces.
// Scans apps/*/CHANGELOG.md and collects likely infra/shared changes.
// Usage: node scripts/generate-workspace-changelog.js [--apply] [--out ./CHANGELOG.md]
const fs = require('fs');
const path = require('path');

const ROOT = process.cwd();
const APPS_DIR = path.join(ROOT, 'apps');
const OUT_FILE = process.argv.includes('--out') ? process.argv[process.argv.indexOf('--out')+1] : path.join(ROOT, 'CHANGELOG.md');
const APPLY = process.argv.includes('--apply');

const KEYWORDS = [
  'nx.json', 'nx', 'monorepo', 'workspace', 'libs/', 'lib/', 'docs/', 'build', 'ci', 'chore(release)', 'version', 'release', 'deploy'
];

function containsKeyword(line) {
  const l = line.toLowerCase();
  return KEYWORDS.some(k => l.includes(k));
}

async function collectFromChangelog(filePath) {
  try {
    const txt = await fs.promises.readFile(filePath, 'utf8');
    const lines = txt.split(/\r?\n/);

    // find Unreleased section first
    const entries = [];
    let inUnreleased = false;
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      if (/^##\s+\[?Unreleased\]?/i.test(line)) {
        inUnreleased = true;
        continue;
      }
      if (inUnreleased) {
        if (/^##\s+\[?\d+/.test(line)) break; // next version
        if (/^\s*-\s+/.test(line) || /^\s*\*/.test(line)) {
          if (containsKeyword(line)) entries.push(line.trim());
        }
      }
    }

    // fallback: scan recent releases for infra keywords
    if (entries.length === 0) {
      let capturing = false;
      for (let i = 0; i < lines.length; i++) {
        const line = lines[i];
        if (/^##\s+\[?\d+/.test(line)) {
          capturing = true; // after first version heading
          continue;
        }
        if (capturing && (/^\s*-\s+/.test(line) || /^\s*\*/.test(line))) {
          if (containsKeyword(line)) entries.push(line.trim());
        }
        if (entries.length >= 20) break;
      }
    }

    return entries;
  } catch (e) {
    return [];
  }
}

async function main() {
  const apps = await fs.promises.readdir(APPS_DIR, { withFileTypes: true });
  const collected = {};

  for (const d of apps) {
    if (!d.isDirectory()) continue;
    const changelogPath = path.join(APPS_DIR, d.name, 'CHANGELOG.md');
    if (fs.existsSync(changelogPath)) {
      const entries = await collectFromChangelog(changelogPath);
      if (entries.length) collected[d.name] = entries;
    }
  }

  // Build workspace changelog content
  const header = `# Monorepo Changelog\n\nThis changelog aggregates infrastructure and shared-library changes across the workspace.\n\n## Unreleased\n\n`;

  const infraHeader = '### Infrastructure & Shared Libraries\n\n';
  let body = header + infraHeader;
  let any = false;
  for (const [app, entries] of Object.entries(collected)) {
    const filtered = entries.filter(Boolean);
    if (filtered.length) {
      any = true;
      body += `- From **${app}**:\n`;
      for (const e of filtered) {
        // normalize leading '- '
        const normalized = e.replace(/^[-*]\s+/, '');
        body += `  - ${normalized}\n`;
      }
      body += '\n';
    }
  }

  if (!any) {
    body += '- No infra/shared-library entries detected in app changelogs.\n\n';
  }

  body += '\n## Notes\n\n- This file is generated by `scripts/generate-workspace-changelog.js`.\n- The generator looks for keywords in app changelogs and aggregates likely workspace-scoped changes.\n';

  if (APPLY) {
    // Simply write the generated content - it includes proper header and structure
    await fs.promises.writeFile(OUT_FILE, body, 'utf8')
    console.log(`Wrote workspace changelog to ${OUT_FILE}`)
  } else {
    console.log(body)
  }
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
